async function rpc(event,payload,requestId=crypto.randomUUID()){
  const response=await fetch(origin+'/api/rpc',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({event,payload,requestId})});
  const reply=await response.json();
  assert.ok(reply.ok,reply.error||'RPC failed: '+event);
  return reply.data;
}
async function rejected(event,payload){
  const response=await fetch(origin+'/api/rpc',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({event,payload,requestId:crypto.randomUUID()})});
  assert.equal((await response.json()).ok,false);
}
